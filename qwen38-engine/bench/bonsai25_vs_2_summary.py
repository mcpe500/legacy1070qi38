def num(s, pat):
    m = re.search(pat, s or "")
    return float(m.group(1)) if m else None


def metric(r, task):
    if not r or not r["st"].startswith("OK") or r["score"] == "none":
        return "-"
    s = r["score"]
    if task == "ppl":
        return "%.3f" % num(s, r"PPL = ([\d.]+)")
    if task == "kld":
        return "%.4f / %.2f %%" % (num(s, r"Mean KLD: ([\d.]+)"), num(s, r"Same top p: ([\d.]+)"))
    if task == "hellaswag":
        return "%.1f (N=%d)" % (num(s, r"acc_norm ([\d.]+)"), r["n"])
    v = num(s, r"Final \w+ score\(\d+ tasks\): ([\d.]+)")
    if v is None:
        v = num(s, r"Final result: ([\d.]+)")
    return "-" if v is None else "%.1f (N=%d)" % (v, r["n"])


