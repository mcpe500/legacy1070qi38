#!/usr/bin/env python3
"""Markdown report + SVG figure for bench/bonsai25_vs_2.sh.   bench/bonsai25_vs_2_summary.py RESULTS_DIR > REPORT.md
Reads RESULTS_DIR/{raw,intel,probe.json,...}. Bonsai 2 numbers come from the same-session runs when they exist,
otherwise from the earlier recorded runs in bench/results (marked with a dagger)."""
import json
import os
import re
import sys

RES = os.path.abspath(sys.argv[1])
BENCH_RES = os.path.dirname(RES)
RAW = os.path.join(RES, "raw")
MIB = 1024.0 * 1024.0


def jlines(path):
    out = []
    try:
        for l in open(path, encoding="utf-8", errors="replace"):
            l = l.strip()
            if l.startswith("{") and l.endswith("}"):
                try:
                    out.append(json.loads(l))
                except ValueError:
                    pass
    except OSError:
        pass
    return out


def get(tag, base=None):
    """-> (engine json or None, wrapper json or None, raw text) of one run."""
    p = os.path.join(base or RAW, tag + ".txt")
    if not os.path.exists(p):
        return None, None, ""
    js = jlines(p)
    eng = next((j for j in js if "tag" not in j), None)
    wrap = next((j for j in js if "tag" in j), None)
    return eng, wrap, open(p, encoding="utf-8", errors="replace").read()


def f(x, nd=2, unit=""):
    return "-" if x is None else ("%.*f%s" % (nd, x, unit))


def vram(w):
    if not w:
        return "-"
    v = w.get("peak_vram_mib", 0)
    return "%d%s" % (v, "" if w.get("vram_cap_ok", True) else " (over cap)")


def rss(w, e=None):
    kb = (w or {}).get("max_rss_kb") or (e or {}).get("peak_rss_kb")
    return "-" if not kb else "%d" % (kb / 1024)


def failed(tag):
    p = os.path.join(RAW, tag + ".fail.txt")
    if os.path.exists(p):
        t = open(p, encoding="utf-8", errors="replace").read().strip().splitlines()
        return "FAILED: " + (t[-1][:90] if t else "")
    return None


def cell(tag, key="decode_tok_s", nd=2):
    e, w, _ = get(tag)
    if e and key in e:
        return f(e[key], nd)
    return failed(tag) or "-"


