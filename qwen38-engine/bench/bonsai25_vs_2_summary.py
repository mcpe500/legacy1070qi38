def parse_lines(path):
    d = {}
    try:
        for l in open(path, encoding="utf-8"):
            m = re.match(r"(\S+): task=(\S+) n=(\d+) ngl=(\d+) score=\[(.*?)\] peak_vram=(\d+) MiB wall=(\d+) s (.*)$", l.strip())
            if m:
                d[m.group(1)] = dict(task=m.group(2), n=int(m.group(3)), ngl=int(m.group(4)), score=m.group(5), vram=int(m.group(6)), wall=int(m.group(7)), st=m.group(8))
    except OSError:
        pass
    return d


old = parse_lines(os.path.join(BENCH_RES, "bonsai", "intel", "run_lines.txt"))
new = parse_lines(os.path.join(RES, "intel", "run_lines.txt"))


def num(s, pat):
    m = re.search(pat, s or "")
    return float(m.group(1)) if m else None


def metric(r, task):
    if not r or not r["st"].startswith("OK") or r["score"] == "none":
        return "-"
    s = r["score"]
    if task == "ppl":
        return "%.3f" % num(s, r"PPL = ([\d.]+)")
    if task == "kld":
        return "%.4f / %.2f %%" % (num(s, r"Mean KLD: ([\d.]+)"), num(s, r"Same top p: ([\d.]+)"))
    if task == "hellaswag":
        return "%.1f (N=%d)" % (num(s, r"acc_norm ([\d.]+)"), r["n"])
    v = num(s, r"Final \w+ score\(\d+ tasks\): ([\d.]+)")
    if v is None:
        v = num(s, r"Final result: ([\d.]+)")
    return "-" if v is None else "%.1f (N=%d)" % (v, r["n"])


