        if e is None:
            P("| %d | %s%s | %s | | | | | | |" % (c, lab, dag, failed(tag) or "no result"))
            continue
        P("| %d | %s%s | %s | %s | %s | %s | %s | %s | %s |" % (c, lab, dag, f(e.get("prefill_tok_s"), 1), f(e.get("decode_tok_s")), vram(w), rss(w), f(e.get("state_mib"), 0), ans, rt))
