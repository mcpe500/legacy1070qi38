# ------------------------------------------------------------------------------------------------ needle
P("## 4. Needle and state round trip (prefill of the whole prompt, then the question from saved state)\n")
P("| ctx | model | prefill tok/s | decode tok/s | peak VRAM MiB | RSS MiB | state MiB | answer | round trip |")
P("|---:|---|---:|---:|---:|---:|---:|---|---|")
