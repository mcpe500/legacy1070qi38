            svg += ['<circle cx="%.0f" cy="%.0f" r="3" fill="%s"/>' % (px(c), py(v), col) for c, v in s]
            svg.append('<text x="%d" y="%d" fill="%s">%s</text>' % (W - 130, 40 + 16 * pts.index((k, s)), col, name))
