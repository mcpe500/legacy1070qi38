series = {"b2": [], "b25": []}
for c in CTXS:
    tags = {k: "%s_d%d_depth" % (k, c) for k in ("b2", "b25", "b25mtp", "b25mtpon")}
    got = {k: get(t) for k, t in tags.items()}
    if not any(g[2] for g in got.values()):
        continue
    e2, w2, _ = got["b2"]; e5, w5, _ = got["b25"]
    r = "-"
    if e2 and e5 and e2.get("decode_tok_s"):
        r = "%.3f" % (e5["decode_tok_s"] / e2["decode_tok_s"])
    for k, e in (("b2", e2), ("b25", e5)):
        if e:
            series[k].append((c, e["decode_tok_s"]))

    def mt(k):
        e, w, _ = got[k]
        return ("%s / %s" % (f(e["decode_tok_s"]), vram(w))) if e else (failed(tags[k]) or "-")
    P("| %d | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (c, cell(tags["b2"]) if e2 else (failed(tags["b2"]) or "-"), cell(tags["b25"]) if e5 else (failed(tags["b25"]) or "-"), r,
                                                              vram(w2), vram(w5), rss(w2, e2), rss(w5, e5), mt("b25mtp"), mt("b25mtpon")))
