def jlines(path):
    out = []
    try:
        for l in open(path, encoding="utf-8", errors="replace"):
            l = l.strip()
            if l.startswith("{") and l.endswith("}"):
                try:
                    out.append(json.loads(l))
                except ValueError:
                    pass
    except OSError:
        pass
    return out


def get(tag, base=None):
    """-> (engine json or None, wrapper json or None, raw text) of one run."""
    p = os.path.join(base or RAW, tag + ".txt")
    if not os.path.exists(p):
        return None, None, ""
    js = jlines(p)
    eng = next((j for j in js if "tag" not in j), None)
    wrap = next((j for j in js if "tag" in j), None)
    return eng, wrap, open(p, encoding="utf-8", errors="replace").read()


def f(x, nd=2, unit=""):
    return "-" if x is None else ("%.*f%s" % (nd, x, unit))


def speed(e, nd=2):
    """Decode tok/s of an engine result, or '0 tokens (stopped)' when the run generated nothing (never 0.00 as a speed)."""
    if not e:
        return "-"
    g = e.get("generated_tokens")
    v = e.get("decode_tok_s")
    if g is not None and g <= 1 and not v:
        return "%d token%s (stopped)" % (g, "" if g == 1 else "s")
    return f(v, nd)


def head_line(tag):
    """The engine's 'LM head:' placement line(s) of a run (from its .err)."""
    out = []
    try:
        for l in open(os.path.join(RAW, tag + ".err"), encoding="utf-8", errors="replace"):
            if l.startswith("LM head:") or l.startswith("--fit-ctx-for-gpu-head") or l.startswith("verify batch lowered"):
                out.append(l.strip())
    except OSError:
        pass
    return out


def vram(w):
    if not w:
        return "-"
    v = w.get("peak_vram_mib", 0)
    return "%d%s" % (v, "" if w.get("vram_cap_ok", True) else " (over cap)")


def rss(w, e=None):
    kb = (w or {}).get("max_rss_kb") or (e or {}).get("peak_rss_kb")
    return "-" if not kb else "%d" % (kb / 1024)


def engine_error(tag):
    """The engine's own error lines of a failed run: the .err before the /usr/bin/time -v block (not the time block itself)."""
    pre = []
    try:
        for l in open(os.path.join(RAW, tag + ".err"), encoding="utf-8", errors="replace"):
            if re.match(r"Command (exited|terminated|being timed)", l):
                break
            if l.strip():
                pre.append(l.strip())
    except OSError:
        pass
    errs = [l for l in pre if re.match(r"(?i)(error|fatal|terminate|cuda error)|out of memory|cudaerror", l)]
    return (errs or pre)[-4:]


def failed(tag):
    p = os.path.join(RAW, tag + ".fail.txt")
    if os.path.exists(p):
        t = engine_error(tag)
        if not t:   # no .err: take the engine lines of fail.txt (everything after the two header lines, before the time block)
            t = [x for x in open(p, encoding="utf-8", errors="replace").read().splitlines()[2:] if not x.startswith("---")][:2]
        return "FAILED: " + (" / ".join(t)[:110] if t else "no engine output")
    return None


def cell(tag, key="decode_tok_s", nd=2):
    e, w, _ = get(tag)
    if e and key in e:
        return f(e[key], nd)
    return failed(tag) or "-"


