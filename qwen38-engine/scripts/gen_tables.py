#!/usr/bin/env python3
"""Generates src/common/tables.inc from the reference sources, so no constant is typed by hand.

  iso3_codebook, iso3_quat_w/x/y/z : docs/ref_pr38_iso3_mtp.diff (PR #38, ground truth for iso3)
  iq3s_grid, kvalues_iq4nl          : ~/llama.cpp/ggml/src/ggml-common.h (baseline tree)

The output uses the macros QT_BEGIN(type, name, size) and QT_END() so the same file serves host code
(static const arrays) and CUDA code (static __device__ const arrays).
Usage: gen_tables.py [--diff PATH] [--common PATH] [--out PATH]
"""
import argparse
import os
import re
import sys

HOME = os.path.expanduser("~")


def extract(text, name, ctype, size):
    m = re.search(r"GGML_TABLE_BEGIN\(\s*%s\s*,\s*%s\s*,\s*(\d+)\s*\)(.*?)GGML_TABLE_END\(\)" % (re.escape(ctype), name),
                  text, re.S)
    if not m:
        sys.exit(f"table {name} not found")
    if int(m.group(1)) != size:
        sys.exit(f"table {name}: size {m.group(1)} != {size}")
    body = "\n".join(l.lstrip("+ ").rstrip() for l in m.group(2).splitlines())
    vals = re.findall(r"-?\d+\.\d+f|-?0x[0-9a-fA-F]+|-?\d+", body)
    if len(vals) != size:
        sys.exit(f"table {name}: parsed {len(vals)} values, expected {size}")
    return vals


def emit(out, ctype, name, vals, per_line):
    out.append(f"QT_BEGIN({ctype}, {name}, {len(vals)})")
    for i in range(0, len(vals), per_line):
        out.append("    " + ", ".join(vals[i:i + per_line]) + ",")
    out.append("QT_END()\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--diff", default="docs/ref_pr38_iso3_mtp.diff")
    ap.add_argument("--common", default=f"{HOME}/llama.cpp/ggml/src/ggml-common.h")
    ap.add_argument("--out", default="src/common/tables.inc")
    a = ap.parse_args()
    diff = open(a.diff, encoding="utf-8").read()
    common = open(a.common, encoding="utf-8").read()
    out = ["// GENERATED by scripts/gen_tables.py. Do not edit by hand.",
           "// iso3 tables come from docs/ref_pr38_iso3_mtp.diff; iq3s_grid and kvalues_iq4nl from ggml-common.h.\n"]
    emit(out, "float", "iso3_codebook", extract(diff, "iso3_codebook", "float", 8), 8)
    for c in "wxyz":
        emit(out, "float", f"iso3_quat_{c}", extract(diff, f"iso3_quat_{c}", "float", 32), 8)
    emit(out, "uint32_t", "iq3s_grid", extract(common, "iq3s_grid", "uint32_t", 512), 8)
    emit(out, "int8_t", "kvalues_iq4nl", extract(common, "kvalues_iq4nl", "int8_t", 16), 16)
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    open(a.out, "w", encoding="utf-8").write("\n".join(out))
    print(f"wrote {a.out} ({sum(1 for l in out if l.startswith('QT_BEGIN'))} tables)")


if __name__ == "__main__":
    main()
